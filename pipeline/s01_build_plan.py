ROOT = Path(__file__).resolve().parent.parent


def validate_frame_dimensions(steps):
    """Reject image/video canvas mismatches before any paid generation."""
    for video in steps.values():
        target = video["params"].get("target")
        if not isinstance(target, dict) or "short_edge" not in target:
            continue
        sizes = []
        for field in ("first_frame", "last_frame"):
            binding = video["inputs"].get(field)
            if not binding:
                continue
            source, _ = reference(binding)
            if source == "input":
                continue  # Imported files are not generated by an upstream step.
            size = steps[source]["params"].get("size")
            if not size:
                continue
            width, height = map(int, size.split("x"))
            if min(width, height) != target["short_edge"]:
                raise ValueError(f"{source}: image size {size} does not match video short_edge={target['short_edge']}; set the image step size explicitly")
            ratio = target.get("aspect_ratio", "auto")
            if ratio != "auto":
                x, y = map(int, ratio.split(":"))
                # Model output dimensions may align the long edge to a block.
                if abs(width - height * x / y) > 32 or (width > height) != (x > y):
                    raise ValueError(f"{source}: image size {size} does not match video aspect_ratio={ratio}")
            sizes.append(size)
        if len(set(sizes)) > 1:
            raise ValueError(f"{video['id']}: first and last frame sizes must be identical")


def identifier(value):
    reserved = {"CON", "PRN", "AUX", "NUL", *(f"COM{i}" for i in range(10)), *(f"LPT{i}" for i in range(10))}
    if (not isinstance(value, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}", value)
            or value.upper() in reserved):
        raise ValueError(f"Invalid identifier: {value!r}")
    return value


def fields(obj, required, optional=()):
    if not isinstance(obj, dict) or set(required) - obj.keys() or obj.keys() - set(required) - set(optional):
        raise ValueError(f"Expected fields {sorted(required)}, optional {sorted(optional)}")


def reference(binding):
    fields(binding, {"ref"})
    if not isinstance(binding["ref"], str):
        raise ValueError("ref must be a string")
    parts = binding["ref"].split(".")
    if len(parts) != 2:
        raise ValueError("ref must be input.FIELD or STEP.OUTPUT")
    for part in parts:
        identifier(part)
    return parts


def build_plan(task_path, *, root=ROOT):
    """No network, environment lookups, output writes, or GPU startup."""
    root = Path(root).resolve()
    task_path = state.local_path(root, task_path)
    task = read_json(task_path)
    fields(task, {"version", "name", "workflow", "items"}, {"project", "scene", "params", "render", "delivery", "delivery_protocol"})
    render = None
    if "render" in task:
        if not isinstance(task["items"], list):
            raise ValueError("Task needs nonempty items")
        from runtime.config.resolution import normalize
        render = normalize(task["render"])
        overrides = [task.get("params", {}), *(item.get("params", {}) for item in task["items"] if isinstance(item, dict))]
        if any(isinstance(params, dict) and {"size", "target"} & params.keys() for params in overrides):
            raise ValueError("render cannot be combined with task/item size or target overrides")
    if not isinstance(task.get("params", {}), dict):
        raise ValueError("Task params must be an object")
    if type(task["version"]) is not int or task["version"] != 1:
        raise ValueError("Unsupported task version")
    identifier(task["name"])
    if not re.fullmatch(r"[0-9]{3}(?:-[a-z0-9]+)+", task["name"]) or task_path.stem != task["name"]:
        raise ValueError("Task name must match filename and use NNN-short-description")
    project = identifier(task.get("project", task["name"]))
    scene = identifier(task.get("scene", "001-main"))
    if not re.fullmatch(r"[0-9]{3}(?:-[a-z0-9]+)+", project):
        raise ValueError("Project must use NNN-short-description")
    if not re.fullmatch(r"[0-9]{3}(?:-[a-z0-9]+)+", scene):
        raise ValueError("Scene must use NNN-short-description")
    workflow_id = identifier(task["workflow"])
    workflow = read_json(state.local_path(root, f"workflows/{workflow_id}.json"))
    fields(workflow, {"version", "id", "steps", "outputs"})
    if type(workflow["version"]) is not int or workflow["version"] != 1 or workflow["id"] != workflow_id:
        raise ValueError("Workflow version or id mismatch")
    if not isinstance(workflow["steps"], list) or not workflow["steps"]:
        raise ValueError("Workflow needs steps")
    if len(workflow["steps"]) != 1 and task.get("params"):
        raise ValueError("For multi-step workflows, put params on workflow steps")
    steps = {}
    for original in workflow["steps"]:
        step = copy.deepcopy(original)
        fields(step, {"id", "uses", "inputs"}, {"params"})
        step_id = identifier(step["id"])
        if step_id == "input" or step_id in steps:
            raise ValueError("Duplicate or reserved step id")
        if step["uses"] not in model_capabilities.CAPABILITIES:
            raise ValueError(f"Unknown capability: {step['uses']}")
        cap = model_capabilities.CAPABILITIES[step["uses"]]
        fields(step["inputs"], cap["required"], {"seed"})
        if not isinstance(step.get("params", {}), dict):
            raise ValueError("Step params must be an object")
        step["supplied_params"] = {**step.get("params", {}), **task.get("params", {})}
        step["params"] = model_capabilities.parameters(step["uses"], step["supplied_params"])
        step["deps"] = []
        steps[step_id] = step
    for step in steps.values():
        for field, binding in step["inputs"].items():
            source, output = reference(binding)
            if source == "input":
                continue
            if source not in steps or output != model_capabilities.CAPABILITIES[steps[source]["uses"]]["output"]:
                raise ValueError(f"Unknown output: {binding}")
            expected = model_capabilities.CAPABILITIES[step["uses"]]["required"].get(field, "integer")
            if output != expected:
                raise ValueError(f"Type mismatch for {step['id']}.{field}")
            if source not in step["deps"]:
                step["deps"].append(source)
    if render is None and all(model_capabilities.CAPABILITIES[s["uses"]]["output"] == "image" for s in steps.values()):
        if not isinstance(task["items"], list):
            raise ValueError("Task needs nonempty items")
        explicit_sizes = any("size" in s["supplied_params"] for s in steps.values()) or any(
            isinstance(item, dict) and isinstance(item.get("params", {}), dict) and "size" in item.get("params", {}) for item in task["items"])
        if not explicit_sizes:
            from runtime.config.resolution import image_size, normalize
            default = normalize({})
            # A global 1K preset must not replace a model's native default
            # (MiniMax, for example, requires at least 4 MP).
            if all(step["params"].get("size") == image_size(default) for step in steps.values()):
                render = default
    if render:
        from runtime.config.resolution import apply_render_preset
        render = apply_render_preset(render, steps, model_capabilities.MODEL_SPECS, model_capabilities.parameters)
    validate_frame_dimensions(steps)
    ordered = []
    while len(ordered) < len(steps):
        ready = [key for key, step in steps.items() if key not in ordered and all(d in ordered for d in step["deps"])]
        if not ready:
            raise ValueError("Workflow has a dependency cycle")
        ordered.extend(ready)
    if not isinstance(workflow["outputs"], dict) or not workflow["outputs"]:
        raise ValueError("Workflow needs named outputs")
    for name, binding in workflow["outputs"].items():
        identifier(name)
        source, output = reference(binding)
        if source not in steps or output != model_capabilities.CAPABILITIES[steps[source]["uses"]]["output"]:
            raise ValueError("Invalid workflow output")
    if not isinstance(task["items"], list) or not task["items"]:
        raise ValueError("Task needs nonempty items")
    ids = set()
    # Windows paths are case insensitive: reject case-only collisions everywhere.
    if len({s.lower() for s in steps}) != len(steps):
        raise ValueError("Case-colliding step IDs")
    jobs, imports = [], {}
    for item in task["items"]:
        if not isinstance(item, dict):
            raise ValueError("Item must be an object")
        if not isinstance(item.get("params", {}), dict):
            raise ValueError("Item params must be an object")
        if len(steps) != 1 and item.get("params"):
            raise ValueError("For multi-step workflows, put params on workflow steps")
        item_id = identifier(item.get("id"))
        if type(item.get("reuse_existing", False)) is not bool:
            raise ValueError("reuse_existing must be a boolean")
        if item_id.lower() in ids:
            raise ValueError("Duplicate item ID")
        ids.add(item_id.lower())
    for step_id in ordered:
        step = steps[step_id]
        cap = model_capabilities.CAPABILITIES[step["uses"]]
        for item in task["items"]:
            inputs = {}
            for field, binding in step["inputs"].items():
                source, key = reference(binding)
                if source != "input":
                    inputs[field] = {"job": f"{source}/{item['id']}", "output": key}
                    continue
                if key not in item:
                    raise ValueError(f"Missing input.{key} in {item['id']}")
                value = item[key]
                expected = cap["required"].get(field, "integer")
                if expected == "string":
                    if not isinstance(value, str) or not value.strip():
                        raise ValueError(f"{key} must be a nonempty string")
                elif expected == "integer":
                    model_capabilities.integer(value, key)
                else:
                    fields(value, {"file"})
                    path = state.local_path(root, value["file"])
                    if not path.is_file() or not 0 < path.stat().st_size <= 20 * 1024 * 1024:
                        raise ValueError(f"Invalid input image: {path}")
                    _, mime = image_format(path.read_bytes())
                    digest = sha256_file(path)
                    value = {"type": "image", "path": f".runner/inputs/{digest}", "sha256": digest,
                             "size": path.stat().st_size, "mime": mime}
                    imports[value["path"]] = {"source": path.relative_to(root).as_posix(), "artifact": value}
                inputs[field] = copy.deepcopy(value)
            if "seed" not in inputs:
                # Stable per identity, independent of item order or batch size.
                seed_scope = step["uses"].split(".")[1] if len(steps) == 1 else step_id
                seed_key = f"{task['name']}/{seed_scope}/{item['id']}".encode()
                inputs["seed"] = int.from_bytes(hashlib.sha256(seed_key).digest()[:4], "big") & 0x7fffffff
                if len(steps) == 1 and "seed" in item:
                    model_capabilities.integer(item["seed"], "seed")
                    if item["seed"] >= 2**32:
                        raise ValueError("seed must be uint32")
                    inputs["seed"] = item["seed"]
            params = model_capabilities.parameters(step["uses"], {**step["supplied_params"], **item.get("params", {})})
            jobs.append({"key": f"{step_id}/{item['id']}", "step": step_id, "item": item["id"],
                         "uses": step["uses"], "params": params, "inputs": inputs,
                         "reuse_existing": item.get("reuse_existing", False)})
    from runtime.config.model_spec import validate
    from runtime.config.storage import runtime_volume_name, VOLUME_SUB_PATH
    specs = {spec["service"]: spec for path in ROOT.glob("models/*/model.json")
             for spec in [validate(read_json(path))]}
    services = {name: {"spec": specs[name]} for name in
                sorted({model_capabilities.CAPABILITIES[j["uses"]]["service"] for j in jobs})}
    plan = {"version": 1, "layout_version": 3, "adapter_version": model_capabilities.VERSION,
            "transport": "sdk", "volume": runtime_volume_name(), "volume_sub_path": VOLUME_SUB_PATH,
            "name": task["name"], "project": project, "scene": scene,
            "workflow": workflow_id, "jobs": jobs, "services": services,
            "outputs": workflow["outputs"], "imports": imports}
    if render:
        plan["render"] = render
    from runtime.delivery.config import configured_delivery, normalize_delivery
    if "delivery" in task:
        plan["delivery"] = normalize_delivery(task["delivery"])
    else:
        configured = configured_delivery(root)
        if configured["provider"] != "local":
            plan["delivery"] = configured
    if "delivery_protocol" in task:
        if type(task["delivery_protocol"]) is not int or task["delivery_protocol"] not in (2, 3):
            raise ValueError("Unsupported delivery protocol")
        if plan.get("delivery", {}).get("provider") not in {"huggingface", "both"}:
            raise ValueError("Durable delivery requires HF destination")
        plan["delivery_protocol"] = task["delivery_protocol"]
        if plan["delivery_protocol"] == 3:
            from runtime.delivery import v3
            plan["delivery_volume"] = v3.volume_name()
            plan["delivery_app"] = v3.app_name()
            if plan["delivery_volume"] == plan["volume"]:
                raise ValueError("V3 requires a separate metadata Volume")
            if not isinstance(task.get("delivery"), dict) or "compression" not in task["delivery"]:
                plan["delivery"]["compression"] = "none"
            plan["delivery"]["verify"] = "sha256"
    plan["hash"] = intent_digest(plan)
    return plan


